-- ── WHY AN EXISTING COLUMN COULD NOT CARRY THIS ──
--
-- Step 5A-4's recovery sweep must visit every unresolved row ACROSS calls, and
-- the fifth review rejected keeping that progress in process memory (a restart,
-- a second instance, or a 65th active mission each wiped it). The progress has to
-- be durable, per row, and monotonically advancing.
--
-- The obvious candidate, `updatedAt`, is the WRONG column for it — on both
-- tables. `updatedAt` is the row's real ACTIVITY timestamp: it is what the
-- command-center's Recent Activity feed orders and dates by
-- (`queries/command-center.ts`), and what "this attempt was last touched" means
-- to a human. A recovery sweep writes nothing; stamping `updatedAt` would make an
-- observation indistinguishable from an execution that actually happened, and
-- would reshuffle an operator's feed every minute. No other existing column is
-- writable without changing the row's meaning (no DROP, no DELETE, no TRUNCATE,
-- no RENAME anywhere, and no ALTER of any table other than the two below), so the
-- smallest correct change is a dedicated nullable key:
--
--   "recoverySweptAt"  NULL = no sweep has ever observed this row, which is
--                      exactly the FRONT of the recovery queue; otherwise the
--                      moment a sweep last observed it.
--
-- It is nullable and has no default ON PURPOSE: NULL must sort first
-- (`ORDER BY "recoverySweptAt" ASC NULLS FIRST`), and it must be impossible for a
-- row to be born already "observed". Both columns are written by exactly one
-- statement each (`markRecoverySwept`), which sets this column and nothing else —
-- no state, no detail, no lease, and not `updatedAt` — using the DATABASE's clock,
-- so two instances cannot disagree about the order of the queue.
--
-- Rules honoured, and checked mechanically by
-- `node scripts/verify-proposed-migration.mjs <this file> --allow=ai_execution_claims,ai_execution_records`:
--
--   * ADDITIVE ONLY: 2× ALTER TABLE ... ADD COLUMN (nullable, no default, so the
--     statement is metadata-only and rewrites no row), 2× CREATE INDEX.
--   * The ALTERs are named explicitly through `--allow`. The verifier's default is
--     "a migration may only ALTER a table it CREATES", and this file creates no
--     table: the two tables it extends are the ones PHASE_2 and PHASE_4 create, and
--     naming them is the human review step the flag exists to force.
--   * No data migration, no backfill, no NOT NULL, no FK, no type change.
--   * Nothing here is registered in `prisma/migrations/`, so `prisma migrate deploy`
--     cannot pick it up by accident.
--
-- ── ACTIVATION REVIEW STILL OWED (stated here, not discovered later) ──
--
--   * These indexes are SINGLE COLUMN. The rotation also orders by `claimedAt`/`id`
--     (claims) and `startedAt`/`id` (records), and every read filters on state/status
