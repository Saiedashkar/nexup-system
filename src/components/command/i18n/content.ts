/**
 * NEXUP COMMAND — DEMO CONTENT OVERLAY (Pass 2)
 * ─────────────────────────────────────────────
 * WHY THIS EXISTS, AND HOW IT DIFFERS FROM `messages.ts`
 * There are two kinds of text in COMMAND, and they need two different mechanisms:
 *
 *   1. CHROME — copy the product owns: navigation, buttons, headings, statuses,
 *      empty/error/loading states, accessible labels. It is finite, it is known
 *      at authoring time, and a missing translation should be impossible. It
 *      lives in `messages.ts` behind typed keys and is read with `t("key")`.
 *
 *   2. CONTENT — the demo *records*: mission titles, decision questions, activity
 *      sentences, system notes, workspace objectives, people roles. There are
 *      ~5,000 of them, they read like data rather than interface, and they are
 *      authored inside the demo dataset where a translation key would be noise.
 *
 *      For these, the English source string IS the key. `CONTENT_AR` maps that
 *      exact source string to Arabic, and `tc(source)` returns the Arabic when
 *      the locale is Arabic and a translation exists — otherwise it returns the
 *      source unchanged. A missing translation therefore degrades to readable
 *      English (honest) rather than to a key name (broken).
 *
 * THIS IS NOT A SECOND LOCALE MECHANISM. There is still exactly one answer to
 * "what language are we in": the `CommandLocaleProvider` store, which already
 * reads and writes `nexup.command.locale`. `tc()` is a *second dictionary read
 * through that same provider* — it holds no state, persists nothing, and cannot
 * disagree with `t()` about the current locale, because both are closures over
 * the same value. Agent Studio consumes it the same way: `const { tc } = useLocale()`.
 *
 * TRANSLATION RULES (same as `messages.ts`)
 *   · Natural professional Arabic, not word-for-word.
 *   · Identifiers stay Latin: NEXUP, COMMAND, EXEC, Hermes, GitHub, Codex, X,
 *     Rebound/REBOUND, model ids (`gpt-5.2`), mission codes (`MIS-2041`),
 *     department codes, currency codes, KPI acronyms.
 *   · A figure stays a figure in both languages; digits remain Western.
 *   · Where a source string embeds an identifier, the Arabic keeps it in place
 *     and the surrounding prose is written so bidi ordering reads correctly.
 */

