/**
 * Translate a demo content string. `source` is the English string as authored in
 * the demo data; the Arabic is returned when the active locale is Arabic and a
 * translation exists. Anything unknown falls through to the source, unchanged.
 */
export function translateContent(
  locale: string,
  source: string,
  translations: Record<string, string> = CONTENT_AR,
): string {
  if (locale !== "ar") return source;
  return translations[source] ?? source;
}

