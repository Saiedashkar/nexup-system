/**
 * NEXUP COMMAND — MESSAGES (Pass 2)
 * ──────────────────────────────────
 * The single dictionary for the Command product. `en` is the SOURCE OF TRUTH:
 * every other locale is typed as `Messages`, the shape derived from `en`, so a
 * missing Arabic key is a *type error* rather than a blank line in the UI. That
 * one rule is why this file exists as plain data instead of a runtime lookup.
 *
 * HOW TO ADD A STRING
 *   1. add it to `en` under the namespace that owns the surface;
 *   2. `tsc` now demands the same key in `ar`;
 *   3. consume it with `const { t } = useLocale(); t("namespace.key")`.
 *
 * TRANSLATION RULES this dictionary keeps:
 *   · Natural, professional Arabic — never word-for-word machine translation.
 *   · Brand and product identifiers are NOT translated: NEXUP, COMMAND, EXEC,
 *     Hermes, Bridge, provider names, model ids, mission codes, department
 *     codes (OPS, GROWTH, …) and the NEXUS token names all stay as written.
 *   · A figure is written as a figure in both languages; a Latin identifier is
 *     emitted through `isolate()` at the call site when it sits inside Arabic
 *     prose, so bidi ordering is decided by the renderer, not by punctuation.
 *   · Placeholders are `{name}` and are interpolated by `t()`.
 */

