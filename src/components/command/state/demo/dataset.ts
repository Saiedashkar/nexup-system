/**
 * NEXUP COMMAND — PRODUCT LAB DEMO DATASET
 * ───────────────────────────────────────
 * One typed dataset, in one file, behind `DemoCommandAdapter`. Components never
 * declare their own sample rows; they read this through the adapter and its
 * selectors, which is what keeps the prototype's surfaces able to disagree about
 * nothing but presentation.
 *
 * PROVENANCE — the three tiers of truth in here, and why:
 *   1. MIRRORED  · the 15 active missions (ids, titles, owners, progress) are
 *      the same missions the department workspaces already own. The Command
 *      Center home reads the workspaces directly, so the mission list has to
 *      agree with it or the prototype contradicts itself.
 *   2. ILLUSTRATIVE · every count, percentage, elapsed time and money figure is
 *      invented for the prototype and labelled as local/demo in the UI.
 *   3. GROUNDED   · the system connection states and their `evidence` strings
 *      describe what is ACTUALLY in this repository (a Bridge package, a Hermes
 *      runtime adapter, an R2/S3 client, a Prisma schema, no Meta/WhatsApp/
 *      GitHub client). An integration is never shown as live because the design
 *      would look nicer if it were.
 *
 * Nothing here fetches, schedules, executes, calls a provider or touches a
 * database. There is no AI behind the EXEC conversation — its replies are
 * deterministic strings chosen from the operating state in this file.
 */

